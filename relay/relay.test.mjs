describe("per-server configuration", () => {
  it("parses an IPv4_port file and resolves a valid secret without exposing it in public fields", () => {
    const config = parseServerConfig("192.0.2.50_60700.cfg", [
      "# Example server", "port=60700", "name=SauerWeb", "domain=example-domain", "envvar=TEST_AUTH_KEY", "autoauth=true",
      "maxclients=2",
    ].join("\n"), { TEST_AUTH_KEY: "2" });
    expect(config).toMatchObject({ host: "192.0.2.50", port: 60700, name: "SauerWeb", domain: "example-domain",
      autoauth: true, maxclients: 2 });
    expect(JSON.stringify({ type: "auth-config", name: config.name, domain: config.domain, autoauth: config.autoauth })).not.toContain("\"2\"");
  });

  it("disables autoauth and warns when the relay secret is absent", () => {
    const config = parseServerConfig("192.0.2.1.cfg", "port=28785\nname=web\ndomain=test\nenvvar=MISSING\nautoauth=true", {});
    expect(config.autoauth).toBe(false);
    expect(config.privateKey).toBeUndefined();
    expect(config.authWarning).toContain("MISSING");
  });

  it("rejects malformed files while continuing to load valid destinations", () => {
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), "sauerweb-config-test-"));
    fs.writeFileSync(path.join(directory, "192.0.2.1.cfg"), "port=28785\nmaxclients=2");
    fs.writeFileSync(path.join(directory, "192.0.2.2.cfg"), "port=invalid");
    const errors = [];
    const configs = loadServerConfigs(directory, {}, { info() {}, warn() {}, error: (message) => errors.push(message) });
    expect([...configs.keys()]).toEqual(["192.0.2.1:28785"]);
    expect(errors[0]).toContain("192.0.2.2.cfg");
    fs.rmSync(directory, { recursive: true, force: true });
  });
});

describe("native Sauerbraten authentication", () => {
  it("matches the NIST P-192 result used by Sauerbraten answerchallenge", () => {
    // Generated by compiling this repository's .Sauerbraten/src/shared/crypto.cpp and invoking answerchallenge() directly.
    const baseX = "188da80eb03090f67cbf20eb43a18800f4ff0afd82ff1012";
    expect(answerChallenge("1", `-${baseX}`)).toBe(baseX);
    expect(answerChallenge("2", `-${baseX}`)).toBe("dafebf5828783f2ad35534631588a3f629a70fb16982a888");
    expect(answerChallenge("1234", `-${baseX}`)).toBe("f36b87c9b3d1282e3ad5292cf398afc333d6219281d3ded4");
    expect(answerChallenge("1c", `-${baseX}`)).toBe("0b0975ea9c391157a409bb07d92e520914b646a2c61d9711");
  });

  it("rejects malformed challenges without including private material in the error", () => {
    expect(() => answerChallenge("secret-value", "+1234")).toThrow("Invalid private key");
  });
});

describe("shared configured-server slots", () => {
  it("counts reservations across limiter instances and makes release idempotent", async () => {
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), "sauerweb-slot-test-"));
    const first = new SharedSlotLimiter(directory), second = new SharedSlotLimiter(directory);
    const one = await first.reserve("192.0.2.1:28785", 2), two = await second.reserve("192.0.2.1:28785", 2);
    expect(one).toBeTruthy();
    expect(two).toBeTruthy();
    expect(await first.reserve("192.0.2.1:28785", 2)).toBeUndefined();
    one.release();
    one.release();
    const replacement = await second.reserve("192.0.2.1:28785", 2);
    expect(replacement).toBeTruthy();
    two.release();
    replacement.release();
    fs.rmSync(directory, { recursive: true, force: true });
  });
});

describe("parseMasterServerList", () => {
  it("parses and deduplicates the original addserver format", () => {
    expect(parseMasterServerList([
      "echo Sauerbraten server list",
      "addserver 192.0.2.1 28785",
      "addserver play.example.net 30000",
      "addserver 192.0.2.1 28785",
      "",
    ].join("\n"))).toEqual([
      { host: "192.0.2.1", port: 28785, label: "192.0.2.1" },
      { host: "play.example.net", port: 30000, label: "play.example.net" },
    ]);
  });

  it("ignores malformed and unsafe destinations", () => {
    expect(parseMasterServerList([
      "addserver example.net 0",
      "addserver example.net 65535",
      "addserver bad/host 28785",
      "addserver -bad.example 28785",
      "addserver example.net not-a-port",
      "addserver example.net 28785 password",
    ].join("\n"))).toEqual([]);
  });
});

describe("resolveClientAddress", () => {
  const request = (remoteAddress, forwarded) => ({
    socket: { remoteAddress },
    headers: forwarded === undefined ? {} : { "x-forwarded-for": forwarded },
  });

  it("uses a forwarded client address only when the direct peer is trusted", () => {
    const trusted = parseTrustedProxies("127.0.0.1/32,::1/128");
    expect(resolveClientAddress(request("127.0.0.1", "203.0.113.8"), trusted)).toBe("203.0.113.8");
    expect(resolveClientAddress(request("198.51.100.4", "203.0.113.8"), trusted)).toBe("198.51.100.4");
  });

  it("walks proxy hops from right to left so a client cannot spoof the leftmost value", () => {
    const trusted = parseTrustedProxies("127.0.0.1/32,10.0.0.0/8");
    expect(resolveClientAddress(request("127.0.0.1", "192.0.2.123, 203.0.113.8"), trusted)).toBe("203.0.113.8");
    expect(resolveClientAddress(request("127.0.0.1", "192.0.2.123, 203.0.113.8, 10.0.0.7"), trusted)).toBe("203.0.113.8");
  });

  it("normalizes IPv4-mapped loopback addresses", () => {
    const trusted = parseTrustedProxies("127.0.0.1/32");
    expect(resolveClientAddress(request("::ffff:127.0.0.1", "203.0.113.8"), trusted)).toBe("203.0.113.8");
  });
});

describe("relay connection limits", () => {
  it("delivers auth configuration before any native server datagram", async () => {
    const udp = dgram.createSocket("udp4");
    await new Promise((resolve) => udp.bind(0, "127.0.0.1", resolve));
    const target = { host: "127.0.0.1", port: udp.address().port, label: "auth-order" };
    udp.on("message", (_datagram, remote) => udp.send(Buffer.from([42]), remote.port, remote.address));
    const server = http.createServer();
    const relay = attachSauerRelay(server, {
      servers: [target], updateServers: async () => [target],
      serverConfigs: new Map([[`${target.host}:${target.port}`, {
        ...target, autoauth: true, name: "relay-user", domain: "example-domain", privateKey: "2",
      }]]),
    });
    await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
    const client = new WebSocket(`ws://127.0.0.1:${server.address().port}/relay?server=${target.host}&port=${target.port}`);
    const messages = [];
    const twoMessages = new Promise((resolve) => client.on("message", (payload, isBinary) => {
      messages.push(isBinary ? Buffer.from(payload) : JSON.parse(payload.toString()));
      if (messages.length === 2) resolve();
    }));
    await opened(client);
    client.send(Buffer.from([1]));
    await twoMessages;
    expect(messages).toEqual([
      { type: "auth-config", name: "relay-user", domain: "example-domain", autoauth: true }, Buffer.from([42]),
    ]);
    client.close();
    relay.close();
    await new Promise((resolve) => server.close(resolve));
    await new Promise((resolve) => udp.close(resolve));
  });

  it("rejects configured-server capacity before creating a relay session and releases the slot on close", async () => {
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), "sauerweb-capacity-test-"));
    const target = { host: "127.0.0.1", port: 28785, label: "limited" };
    const server = http.createServer();
    const relay = attachSauerRelay(server, {
      servers: [target], updateServers: async () => [target], slotDirectory: directory,
      serverConfigs: new Map([["127.0.0.1:28785", { ...target, autoauth: false, maxclients: 1 }]]),
    });
    await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
    const url = `ws://127.0.0.1:${server.address().port}/relay?server=${target.host}&port=${target.port}`;
    const first = new WebSocket(url);
    await opened(first);
    const blocked = new WebSocket(url), capacity = nextJsonMessage(blocked, "server-capacity");
    await opened(blocked);
    await expect(capacity).resolves.toEqual({
      type: "server-capacity", message: "Server capacity reached. Try another server or use the original Sauerbraten client.",
    });
    await new Promise((resolve) => { first.once("close", resolve); first.close(); });
    const replacement = new WebSocket(url);
    await opened(replacement);
    replacement.close();
    blocked.terminate();
    relay.close();
    await new Promise((resolve) => server.close(resolve));
    fs.rmSync(directory, { recursive: true, force: true });
  });

  it("scopes teamkill disconnects and cooldowns to one browser address and native target", async () => {
    const target = { host: "127.0.0.1", port: 28785, label: "test" };
    const server = http.createServer();
    const relay = attachSauerRelay(server, {
      servers: [target],
      trustedProxies: "127.0.0.1/32",
      updateServers: async () => [target],
      teamkillProtection: { warningThreshold: 2, disconnectThreshold: 3, windowMilliseconds: 60_000, cooldownMilliseconds: 60_000 },
    });
    await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
    const url = `ws://127.0.0.1:${server.address().port}/relay?server=${target.host}&port=${target.port}`;
    const offenderOptions = { headers: { "X-Forwarded-For": "203.0.113.8" } };
    const innocentOptions = { headers: { "X-Forwarded-For": "198.51.100.9" } };
    const offender = new WebSocket(url, offenderOptions), innocent = new WebSocket(url, innocentOptions);
    await Promise.all([opened(offender), opened(innocent)]);
    const warning = nextJsonMessage(offender, "teamkill-warning");
    offender.send(JSON.stringify({ type: "teamkill" }));
    offender.send(JSON.stringify({ type: "teamkill" }));
    await expect(warning).resolves.toEqual({ type: "teamkill-warning", count: 2 });
    const disconnected = nextJsonMessage(offender, "teamkill-disconnect");
    const offenderClosed = new Promise((resolve) => offender.once("close", resolve));
    offender.send(JSON.stringify({ type: "teamkill" }));
    await expect(disconnected).resolves.toEqual({ type: "teamkill-disconnect", cooldownMilliseconds: 60_000 });
    await offenderClosed;
    expect(innocent.readyState).toBe(WebSocket.OPEN);

    const innocentReconnect = new WebSocket(url, innocentOptions);
    await opened(innocentReconnect);
    const blocked = new WebSocket(url, offenderOptions);
    const cooldown = nextJsonMessage(blocked, "teamkill-disconnect");
    await opened(blocked);
    await expect(cooldown).resolves.toMatchObject({ type: "teamkill-disconnect" });
    innocent.terminate();
    innocentReconnect.terminate();
    blocked.terminate();
    relay.close();
    await new Promise((resolve) => server.close(resolve));
  });

  it("atomically limits concurrent upgrades to four connections per resolved client address", async () => {
    const target = { host: "127.0.0.1", port: 28785, label: "test" };
    let finishRefresh;
    const refresh = new Promise((resolve) => { finishRefresh = resolve; });
    const server = http.createServer();
    const relay = attachSauerRelay(server, {
      servers: [],
      trustedProxies: "127.0.0.1/32",
      updateServers: () => refresh,
    });
    await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
    const { port } = server.address();
    const clientAddresses = [...Array.from({ length: 5 }, () => "203.0.113.8"), "198.51.100.9"];
    const clients = clientAddresses.map((address) => new WebSocket(
      `ws://127.0.0.1:${port}/relay?server=${target.host}&port=${target.port}`,
      { headers: { "X-Forwarded-For": address } },
    ));
    const outcomes = clients.map((client) => new Promise((resolve) => {
      client.once("open", () => resolve(101));
      client.once("unexpected-response", (_request, response) => { response.resume(); resolve(response.statusCode); });
      client.once("error", () => resolve(0));
    }));
    finishRefresh([target]);
    expect((await Promise.all(outcomes)).sort()).toEqual([101, 101, 101, 101, 101, 403]);
    await Promise.all(clients.filter((client) => client.readyState === WebSocket.OPEN).map((client) => new Promise((resolve) => {
      client.once("close", resolve);
      client.close();
    })));
    relay.close();
    await new Promise((resolve) => server.close(resolve));
  });

  it("preserves complete binary datagrams in both directions", async () => {
    const udp = dgram.createSocket("udp4");
    await new Promise((resolve) => udp.bind(0, "127.0.0.1", resolve));
    const target = { host: "127.0.0.1", port: udp.address().port, label: "echo" };
    udp.on("message", (datagram, remote) => udp.send(datagram, remote.port, remote.address));
    const server = http.createServer();
    const relay = attachSauerRelay(server, { servers: [target], updateServers: async () => [target] });
    await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
    const client = new WebSocket(`ws://127.0.0.1:${server.address().port}/relay?server=${target.host}&port=${target.port}`);
    await new Promise((resolve, reject) => {
      client.once("open", resolve);
      client.once("error", reject);
    });
    const sent = Buffer.from([0xFF, 0x00, 0x80, 0x01, 0x7F]);
    const received = new Promise((resolve, reject) => {
      client.once("message", (datagram, isBinary) => isBinary ? resolve(Buffer.from(datagram)) : reject(new Error("Text relay frame")));
      client.once("error", reject);
    });
    client.send(sent, { binary: true });
    await expect(received).resolves.toEqual(sent);
    await new Promise((resolve) => { client.once("close", resolve); client.close(); });
    relay.close();
    await new Promise((resolve) => server.close(resolve));
    await new Promise((resolve) => udp.close(resolve));
  });

  it("forwards browser-timed server-info probes to the vanilla info port", async () => {
    const info = dgram.createSocket("udp4");
    await new Promise((resolve) => info.bind(0, "127.0.0.1", resolve));
    const target = { host: "127.0.0.1", port: info.address().port - 1, label: "info" };
    info.on("message", (datagram, remote) => info.send(datagram, remote.port, remote.address));
    const server = http.createServer();
    const relay = attachSauerRelay(server, { servers: [target], updateServers: async () => [target] });
    await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
    const client = new WebSocket(
      `ws://127.0.0.1:${server.address().port}/relay?server=${target.host}&port=${target.port}&info=1`,
    );
    await opened(client);
    const received = new Promise((resolve) => client.once("message", (datagram) => resolve(Buffer.from(datagram))));

    client.send(Buffer.from([42]));

    await expect(received).resolves.toEqual(Buffer.from([42]));
    await new Promise((resolve) => { client.once("close", resolve); client.close(); });
    relay.close();
    await new Promise((resolve) => server.close(resolve));
    await new Promise((resolve) => info.close(resolve));
  });
});

